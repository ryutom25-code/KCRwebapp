-- Test-only schema inferred from the columns referenced by the frontend.
-- This file must only be loaded into a disposable database.
create schema auth;
create schema storage;
do $$ begin
  if not exists(select 1 from pg_roles where rolname='anon') then create role anon; end if;
  if not exists(select 1 from pg_roles where rolname='authenticated') then create role authenticated; end if;
end $$;
grant usage on schema public, auth, storage to anon, authenticated;
create function auth.uid() returns uuid language sql stable as $$
  select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid;
$$;
create table auth.users(id uuid primary key,email text unique);
create table public.profiles(id uuid primary key references auth.users(id),name text,school_name text,grade text,
  points integer default 0,created_at timestamptz default now());
create table public.checkins(id uuid primary key default gen_random_uuid(),user_id uuid references public.profiles(id),
  booth_id text,created_at timestamptz default now());
-- Column types confirmed from the supplied Supabase screenshot.
-- Identity, timestamp default and FK are test assumptions, not confirmed production settings.
create table public.point_history(id bigint generated by default as identity primary key,user_id uuid references public.profiles(id),
  title text,category text,points integer,created_at timestamptz default now(),department_name text,is_delivered boolean);
create table public.products(id uuid primary key default gen_random_uuid(),name text,points integer,image_url text,
  created_at timestamptz default now(),updated_at timestamptz default now());
create table public.events(id uuid primary key default gen_random_uuid(),title text,event_date date,is_new boolean,
  created_at timestamptz default now(),updated_at timestamptz default now());
create table public.quiz_sets(id uuid primary key default gen_random_uuid(),department text,title text,created_at timestamptz default now());
create table public.quizzes(id uuid primary key default gen_random_uuid(),set_id uuid references public.quiz_sets(id),
  question text,options __OPTIONS_TYPE__,correct_index integer,points integer default 10);
create table public.quiz_answers(id uuid primary key default gen_random_uuid(),user_id uuid references public.profiles(id),
  set_id uuid references public.quiz_sets(id),quiz_id uuid references public.quizzes(id),is_correct boolean,created_at timestamptz default now());
create table storage.objects(id uuid primary key default gen_random_uuid(),bucket_id text,name text);
alter table storage.objects enable row level security;
grant select, insert, update, delete on storage.objects to anon, authenticated;
-- Simulate legacy permissive policies and column privileges that must be removed/contained.
create policy legacy_storage on storage.objects for all to anon, authenticated using(true) with check(true);
grant select, insert, update, delete on all tables in schema public to anon, authenticated;
grant update(points), insert(points) on public.profiles to authenticated;
grant select(correct_index) on public.quizzes to authenticated;
alter table public.profiles enable row level security;
create policy legacy_profiles on public.profiles for all to anon, authenticated using(true) with check(true);
